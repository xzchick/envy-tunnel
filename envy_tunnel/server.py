"""Set up and manage the WireGuard server on a Linux VPS you control.

ENVY Tunnel never invents a VPN protocol: the server runs the standard Linux
WireGuard (kernel module + ``wg-quick``), managed by systemd where present. This
module only *writes the shell scripts* that do it, then runs them over your own
``ssh`` (the OpenSSH client on macOS, Linux and Windows 10+), so your SSH keys,
``known_hosts`` and agent work exactly as they always do. ENVY never asks for or
stores a server password.

Every script is idempotent, can be printed instead of run (paste it into your
provider's web console), and refuses to touch a WireGuard interface that ENVY
didn't create.
"""

from __future__ import annotations

import shlex
import subprocess
from dataclasses import dataclass

from . import __version__
from .model import Server, State, TunnelError, server_peers_block

MARK_KEY = "ENVY-SERVER-PUBLIC-KEY"
MARK_OK = "ENVY-OK"
MARK_ERR = "ENVY-ERROR"
MARK_STEP = "ENVY-STEP"

_PRELUDE = r"""#!/usr/bin/env bash
# ENVY Tunnel server {action} script, generated by envy-tunnel {version}.
# Safe to read before running; safe to run more than once.
set -euo pipefail
umask 077
WG_IF={iface}
WG_PORT={port}
ADDR4={addr4}
ADDR6={addr6}
NET4={net4}
NET6={net6}
DIR=/etc/wireguard
say()  {{ printf '{step} %s\n' "$*"; }}
fail() {{ printf '{err} %s\n' "$*"; exit 3; }}
has_systemd() {{ command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; }}
[ "$(uname -s)" = Linux ] || fail "the server must run Linux"
[ "$(id -u)" -eq 0 ] || fail "needs root: connect as root, or as a user with passwordless sudo"
"""

_SETUP = r"""
if [ -f "$DIR/$WG_IF.conf" ] && [ ! -f "$DIR/$WG_IF.envy-interface" ]; then
  fail "$WG_IF is already configured by something other than ENVY Tunnel; pick another interface name"
fi

if command -v wg >/dev/null 2>&1 && command -v wg-quick >/dev/null 2>&1 && command -v iptables >/dev/null 2>&1; then
  say "WireGuard tools already installed"
else
  say "Installing WireGuard tools"
  if command -v apt-get >/dev/null 2>&1; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq && apt-get install -y -qq wireguard-tools iptables >/dev/null
  elif command -v dnf >/dev/null 2>&1; then dnf install -y -q wireguard-tools iptables
  elif command -v yum >/dev/null 2>&1; then yum install -y -q wireguard-tools iptables
  elif command -v pacman >/dev/null 2>&1; then pacman -Sy --noconfirm --needed wireguard-tools iptables
  elif command -v zypper >/dev/null 2>&1; then zypper --non-interactive install wireguard-tools iptables
  elif command -v apk >/dev/null 2>&1; then apk add --no-cache wireguard-tools iptables ip6tables
  else fail "unsupported Linux distribution (no apt, dnf, yum, pacman, zypper or apk)"
  fi
fi

if ! ip link show "$WG_IF" >/dev/null 2>&1; then
  ip link add dev envy-probe type wireguard 2>/dev/null \
    || fail "this server's kernel has no WireGuard support (common on OpenVZ/LXC container VPSes; use a KVM VPS)"
  ip link del dev envy-probe
fi

EXT_IF=$(ip -4 route show default | awk '{for (i = 1; i < NF; i++) if ($i == "dev") { print $(i + 1); exit }}')
[ -n "$EXT_IF" ] || fail "could not find the server's default network interface"
say "Internet-facing interface: $EXT_IF"

HAVE6=0
if [ -f /proc/net/if_inet6 ] && command -v ip6tables >/dev/null 2>&1; then HAVE6=1; fi

mkdir -p "$DIR"; chmod 700 "$DIR"
if [ ! -s "$DIR/$WG_IF.key" ]; then
  say "Generating the server key (it never leaves this server)"
  wg genkey > "$DIR/$WG_IF.key"
fi
chmod 600 "$DIR/$WG_IF.key"

UP="iptables -t nat -A POSTROUTING -s $NET4 -o $EXT_IF -j MASQUERADE; iptables -I FORWARD 1 -i %i -j ACCEPT; iptables -I FORWARD 1 -o %i -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT; iptables -I INPUT 1 -p udp --dport $WG_PORT -j ACCEPT"
DOWN="iptables -t nat -D POSTROUTING -s $NET4 -o $EXT_IF -j MASQUERADE; iptables -D FORWARD -i %i -j ACCEPT; iptables -D FORWARD -o %i -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT; iptables -D INPUT -p udp --dport $WG_PORT -j ACCEPT"
ADDRS="$ADDR4"
if [ "$HAVE6" = 1 ]; then
  ADDRS="$ADDR4, $ADDR6"
  UP="$UP; ip6tables -t nat -A POSTROUTING -s $NET6 -o $EXT_IF -j MASQUERADE; ip6tables -I FORWARD 1 -i %i -j ACCEPT; ip6tables -I FORWARD 1 -o %i -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT"
  DOWN="$DOWN; ip6tables -t nat -D POSTROUTING -s $NET6 -o $EXT_IF -j MASQUERADE; ip6tables -D FORWARD -i %i -j ACCEPT; ip6tables -D FORWARD -o %i -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT"
fi

{
  printf '# Managed by ENVY Tunnel. Device list lives in %s.envy-peers.\n' "$WG_IF"
  printf '[Interface]\nAddress = %s\nListenPort = %s\nPrivateKey = %s\nPostUp = %s\nPostDown = %s\n' \
    "$ADDRS" "$WG_PORT" "$(cat "$DIR/$WG_IF.key")" "$UP" "$DOWN"
} > "$DIR/$WG_IF.envy-interface"

say "Enabling IP forwarding"
{
  echo "net.ipv4.ip_forward = 1"
  if [ "$HAVE6" = 1 ]; then echo "net.ipv6.conf.all.forwarding = 1"; fi
} > /etc/sysctl.d/99-envy-tunnel.conf
sysctl -q -p /etc/sysctl.d/99-envy-tunnel.conf >/dev/null

if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  say "Opening UDP $WG_PORT in ufw"
  ufw allow "$WG_PORT/udp" >/dev/null
fi
if command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
  say "Opening UDP $WG_PORT in firewalld"
  firewall-cmd -q --permanent --add-port="$WG_PORT/udp"
  firewall-cmd -q --permanent --add-masquerade
  firewall-cmd -q --permanent --zone=trusted --add-interface="$WG_IF" || true
  firewall-cmd -q --reload
fi
RESTART=1
"""

_SYNC = r"""
RESTART=${{RESTART:-0}}
[ -f "$DIR/$WG_IF.envy-interface" ] || fail "this server isn't set up for ENVY Tunnel yet; run setup first"
say "Writing the device list ({count} device(s))"
cat > "$DIR/$WG_IF.envy-peers" <<'ENVY_PEERS_END'
{peers}
ENVY_PEERS_END
{{ cat "$DIR/$WG_IF.envy-interface"; echo; cat "$DIR/$WG_IF.envy-peers"; }} > "$DIR/$WG_IF.conf.new"
chmod 600 "$DIR/$WG_IF.conf.new"
mv -f "$DIR/$WG_IF.conf.new" "$DIR/$WG_IF.conf"

if ip link show "$WG_IF" >/dev/null 2>&1 && [ "$RESTART" = 0 ]; then
  wg syncconf "$WG_IF" <(wg-quick strip "$WG_IF")
  say "Applied live (no restart, connected devices stay connected)"
elif has_systemd; then
  systemctl enable "wg-quick@$WG_IF" >/dev/null 2>&1 || true
  systemctl restart "wg-quick@$WG_IF"
  say "WireGuard started with systemd (and enabled at boot)"
else
  wg-quick down "$WG_IF" >/dev/null 2>&1 || true
  wg-quick up "$WG_IF" >/dev/null
  say "WireGuard started (no systemd: add 'wg-quick up $WG_IF' to your boot scripts)"
fi
printf '{key} %s\n' "$(wg show "$WG_IF" public-key)"
echo {ok}
"""

_STATUS = r"""
ip link show "$WG_IF" >/dev/null 2>&1 || fail "WireGuard interface $WG_IF is not running on the server"
echo ENVY-DUMP-BEGIN
wg show "$WG_IF" dump
echo ENVY-DUMP-END
printf '{key} %s\n' "$(wg show "$WG_IF" public-key)"
echo {ok}
"""

_UNINSTALL = r"""
[ -f "$DIR/$WG_IF.envy-interface" ] || fail "no ENVY Tunnel setup found for $WG_IF"
if has_systemd; then systemctl disable --now "wg-quick@$WG_IF" >/dev/null 2>&1 || true; fi
wg-quick down "$WG_IF" >/dev/null 2>&1 || true
rm -f "$DIR/$WG_IF.conf" "$DIR/$WG_IF.key" "$DIR/$WG_IF.envy-interface" "$DIR/$WG_IF.envy-peers" /etc/sysctl.d/99-envy-tunnel.conf
say "Removed the ENVY Tunnel WireGuard setup (packages were left installed)"
echo {ok}
"""


def _prelude(server: Server, action: str) -> str:
    server.validate()
    q = shlex.quote
    return _PRELUDE.format(action=action, version=__version__, iface=q(server.interface),
                           port=server.wg_port, addr4=q(str(server.gateway4())),
                           addr6=q(str(server.gateway6())), net4=q(server.subnet4),
                           net6=q(server.subnet6), step=MARK_STEP, err=MARK_ERR)


def _sync_body(state: State, preshared: dict) -> str:
    return _SYNC.format(count=len(state.devices), peers=server_peers_block(state, preshared).rstrip("\n"),
                        key=MARK_KEY, ok=MARK_OK)


def setup_script(state: State, preshared: dict) -> str:
    """Install WireGuard, create the interface, NAT and forwarding, and load the devices."""
    return _prelude(state.server, "setup") + _SETUP + _sync_body(state, preshared)


def sync_script(state: State, preshared: dict) -> str:
    """Replace the server's device list with this computer's and apply it live."""
    return _prelude(state.server, "sync") + _sync_body(state, preshared)


def status_script(state: State) -> str:
    return _prelude(state.server, "status") + _STATUS.format(key=MARK_KEY, ok=MARK_OK)


def uninstall_script(state: State) -> str:
    return _prelude(state.server, "uninstall") + _UNINSTALL.format(ok=MARK_OK)


def ssh_argv(server: Server, interactive: bool = False, ssh: str = "ssh") -> list[str]:
    """The ssh command that runs a script from stdin as root on the server."""
    server.validate()
    argv = [ssh, "-p", str(server.ssh_port), "-o", "ConnectTimeout=15",
            "-o", "StrictHostKeyChecking=accept-new"]
    if not interactive:
        argv += ["-o", "BatchMode=yes"]
    if server.ssh_key:
        argv += ["-i", server.ssh_key, "-o", "IdentitiesOnly=yes"]
    argv.append(f"{server.ssh_user}@{server.host}")
    argv.append("bash -s" if server.ssh_user == "root" else "sudo -n bash -s")
    return argv


@dataclass
class Result:
    ok: bool
    steps: list
    server_key: str
    stdout: str
    stderr: str


def default_runner(argv: list[str], stdin: str, timeout: int) -> tuple[int, str, str]:
    try:
        proc = subprocess.run(argv, input=stdin, capture_output=True, text=True, timeout=timeout)
    except FileNotFoundError:
        raise TunnelError("The 'ssh' command was not found. On Windows, turn on "
                          "Settings → Optional features → OpenSSH Client.") from None
    except subprocess.TimeoutExpired:
        raise TunnelError(f"The server did not finish within {timeout} seconds.") from None
    return proc.returncode, proc.stdout, proc.stderr


def parse_output(code: int, stdout: str, stderr: str) -> Result:
    steps, key, error = [], "", ""
    for line in stdout.splitlines():
        if line.startswith(MARK_STEP + " "):
            steps.append(line[len(MARK_STEP) + 1:])
        elif line.startswith(MARK_KEY + " "):
            key = line[len(MARK_KEY) + 1:].strip()
        elif line.startswith(MARK_ERR + " "):
            error = line[len(MARK_ERR) + 1:]
    ok = code == 0 and MARK_OK in stdout.splitlines()
    if error:
        raise TunnelError(f"Server: {error}")
    if code == 255:
        tail = stderr.strip().splitlines()[-1:] or ["no details"]
        raise TunnelError("Could not connect over SSH: " + tail[0] + ". Check the host, user and "
                          "SSH key, and that you can run `ssh user@host` yourself.")
    if "sudo:" in stderr and "password" in stderr:
        raise TunnelError("sudo needs a password on the server. Connect as root, or allow "
                          "passwordless sudo for this user, or run the printed script yourself.")
    if not ok:
        tail = "\n".join((stderr or stdout).strip().splitlines()[-5:])
        raise TunnelError(f"The server script failed (exit {code}).\n{tail}".rstrip())
    return Result(ok=True, steps=steps, server_key=key, stdout=stdout, stderr=stderr)


def dump_section(stdout: str) -> str:
    lines = stdout.splitlines()
    try:
        start, end = lines.index("ENVY-DUMP-BEGIN"), lines.index("ENVY-DUMP-END")
    except ValueError:
        return ""
    return "\n".join(lines[start + 1:end])
